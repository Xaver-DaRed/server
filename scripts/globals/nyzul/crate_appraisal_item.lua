local setupCrateContent = function(npc)
    -- Build item table.
    local dTableCrateItems = {}
    local randomIndex      = 0
    local itemEntry        = 0

    for i = 1, #crateItems do
        table.insert(dTableCrateItems, i)
    end


    -- Setup first item.
    if npc:getLocalVar('[Crate]Item1') == 0 then
        randomIndex = math.random(1, #dTableCrateItems)
        itemEntry   = dTableCrateItems[randomIndex]

        npc:setLocalVar('[Crate]Item1', itemEntry.itemID)
        npc:setLocalVar('[Crate]Amount1', itemEntry.amount)
        table.remove(dTableCrateItems, randomIndex)
    end

    -- Setup second item.
    local item2Random = math.random(1, 100)

    if item2Random <= 50 then
        randomIndex = math.random(1, #dTableCrateItems)
        itemEntry   = dTableCrateItems[randomIndex]

        npc:setLocalVar('[Crate]Item2', itemEntry.itemID)
        npc:setLocalVar('[Crate]Amount2', itemEntry.amount)
        table.remove(dTableCrateItems, randomIndex)
    end

    -- Setup third item.
    local item3Random = math.random(1, 100)

    if item2Random <= 50 and item3Random <= 50 then
        randomIndex = math.random(1, #dTableCrateItems)
        itemEntry   = dTableCrateItems[randomIndex]

        npc:setLocalVar('[Crate]Item3', itemEntry.itemID)
        npc:setLocalVar('[Crate]Amount3', itemEntry.amount)
        table.remove(dTableCrateItems, randomIndex)
    end
end

xi.nyzul.spawnChest = function(mob, player)
    local instance = mob:getInstance()
    local mobID    = mob:getID()

    -- NM chest spawn.
    if
        mobID >= ID.mob[51].OFFSET_NM and
        mobID <= ID.mob[51].TAISAIJIN
    then
        for _, cofferID in ipairs(ID.npc.TREASURE_COFFER) do
            local coffer = GetNPCByID(cofferID, instance)

            if coffer:getStatus() == xi.status.DISAPPEAR then
                local pos = mob:getPos()
                coffer:setUntargetable(false)
                coffer:setPos(pos.x, pos.y, pos.z, pos.rot)
                coffer:setLocalVar('appraisalItem', mobID)
                coffer:setStatus(xi.status.NORMAL)

                break
            end
        end

    -- NM casket spawn.
    elseif
        mobID < ID.mob[51].ADAMANTOISE and
        xi.settings.main.ENABLE_NYZUL_CASKETS
    then
        if math.random(1, 100) <= 6 then
            for _, casketID in ipairs(ID.npc.TREASURE_CASKET) do
                local casket = GetNPCByID(casketID, instance)

                if casket:getStatus() == xi.status.DISAPPEAR then
                    local pos = mob:getPos()
                    casket:setPos(pos.x, pos.y, pos.z, pos.rot)
                    casket:setStatus(xi.status.NORMAL)

                    break
                end
            end
        end
    end
end

xi.nyzul.vigilWeaponCrateOnTrigger = function(player, npc)
    local instance = npc:getInstance()
    local chars    = instance:getChars()

    for _, cofferID in ipairs(ID.npc.TREASURE_COFFER) do
        if npc:getID() == cofferID and npc:getLocalVar('opened') == 0 then
            -- Appraisal Items
            local mobOffset = npc:getLocalVar('appraisalItem') - (ID.mob[51].OFFSET_NM - xi.appraisal.origin.NYZUL_BAT_EYE) -- Bat Eye mobId - Appraisal mob value.

            if mobOffset == 166 or mobOffset == 187 then
                mobOffset = 108
            elseif mobOffset == 154 or mobOffset == 172 or mobOffset == 190 then
                mobOffset = 136
            end

            local itemID = appraisalItems[mobOffset]

            if type(itemID) == 'table' then
                local pick = math.random(1, #itemID)
                itemID     = itemID[pick]
            end

            if player:getFreeSlotsCount() == 0 then
                player:messageSpecial(ID.text.ITEM_CANNOT_BE_OBTAINED, itemID)

                return
            end

            player:addItem({ id = itemID, appraisal = mobOffset })

            for _, players in pairs(chars) do
                players:messageName(ID.text.PLAYER_OBTAINS_ITEM, player, itemID)
            end

            npc:entityAnimationPacket(xi.animationString.OPEN_CRATE_GLOW)
            npc:setLocalVar('opened', 1)
            npc:setUntargetable(true)
            npc:queue(10000, function(npcvar)
                npcvar:entityAnimationPacket(xi.animationString.STATUS_DISAPPEAR)
            end)

            npc:queue(12000, function(npcvar)
                npcvar:setStatus(xi.status.DISAPPEAR)
                npcvar:resetLocalVars()
                npcvar:setAnimationSub(0)
            end)

            break
        end
    end
end

xi.nyzul.temporalItemCrateOnTrigger = function(player, npc)
    if npc:getLocalVar('[Crate]Setup') == 0 then
        npc:setLocalVar('[Crate]Setup', 1)
        npc:entityAnimationPacket(xi.animationString.OPEN_CRATE_GLOW)
        npc:setAnimationSub(13)
        setupCrateContent(npc)
    end

    local paramOne   = npc:getLocalVar('[Crate]Item1') + npc:getLocalVar('[Crate]Amount1') * 65536
    local paramTwo   = npc:getLocalVar('[Crate]Item2') + npc:getLocalVar('[Crate]Amount2') * 65536
    local paramThree = npc:getLocalVar('[Crate]Item3') + npc:getLocalVar('[Crate]Amount3') * 65536

    player:startEvent(2, paramOne, paramTwo, paramThree, 0, 0, 0, 0, 0)









    local npcID = npc:getID()

    if
        npcID == 17092611 or
        npcID == 17092612 or
        npcID == 17092614
    then
        xi.nyzul.handleAppraisalItem(player, npc)
    else
        xi.nyzul.tempBoxTrigger(player, npc)
    end
end

xi.nyzul.temporalItemCrateOnEventFinish = function(player, csid, option, npc)
    if csid == 2 then
        local item1 = npc:getLocalVar('[Crate]Item1')
        local item2 = npc:getLocalVar('[Crate]Item2')
        local item3 = npc:getLocalVar('[Crate]Item3')

        if
            option == 1 and
            item1 > 0 and
            npc:getLocalVar('[Crate]Amount1') > 0
        then
            if not player:hasItem(item1, xi.inventoryLocation.TEMPITEMS) then
                player:addTempItem(item1)
                player:messageName(ID.text.PLAYER_OBTAINS_TEMP_ITEM, player, item1)
                npc:setLocalVar('[Crate]Amount1', npc:getLocalVar('[Crate]Amount1') - 1)
            else
                player:messageSpecial(ID.text.ALREADY_HAVE_TEMP_ITEM)
            end

        elseif
            option == 2 and
            item2 > 0 and
            npc:getLocalVar('[Crate]Amount2') > 0
        then
            if not player:hasItem(item2, xi.inventoryLocation.TEMPITEMS) then
                player:addTempItem(item2)
                player:messageName(ID.text.PLAYER_OBTAINS_TEMP_ITEM, player, item2)
                npc:setLocalVar('[Crate]Amount2', npc:getLocalVar('[Crate]Amount2') - 1)
            else
                player:messageSpecial(ID.text.ALREADY_HAVE_TEMP_ITEM)
            end

        elseif
            option == 3 and
            item3 > 0 and
            npc:getLocalVar('[Crate]Amount3') > 0
        then
            if not player:hasItem(item3, xi.inventoryLocation.TEMPITEMS) then
                player:addTempItem(item3)
                player:messageName(ID.text.PLAYER_OBTAINS_TEMP_ITEM, player, item3)
                npc:setLocalVar('[Crate]Amount3', npc:getLocalVar('[Crate]Amount3') - 1)
            else
                player:messageSpecial(ID.text.ALREADY_HAVE_TEMP_ITEM)
            end
        end

        if
            npc:getLocalVar('[Crate]Amount1') == 0 and
            npc:getLocalVar('[Crate]Amount2') == 0 and
            npc:getLocalVar('[Crate]Amount3') == 0
        then
            npc:queue(10000, function(npcvar)
                npcvar:entityAnimationPacket(xi.animationString.STATUS_DISAPPEAR)
            end)

            npc:queue(12000, function(npcvar)
                npcvar:setStatus(xi.status.DISAPPEAR)
                npcvar:setAnimationSub(0)
                npcvar:resetLocalVars()
            end)
        end
    end
end

